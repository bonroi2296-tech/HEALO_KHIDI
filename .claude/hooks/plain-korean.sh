#!/usr/bin/env bash
# 「쉬운 말 + 원어 병기」를 매 턴 다시 띄운다 — 세션 시작 1회로는 희석돼서 안 지켜진다.
#
# 왜 (2026-07-28 PO 지적, 한 시간에 두 번 어김):
#   규칙은 대화 맨 앞 한 줄인데, 그 뒤로 셸 스크립트·설정·로그 수만 자가 쌓인다.
#   말투는 「방금 읽은 것」에 끌려가므로, 기술 작업이 깊어질수록 말이 어려워진다 —
#   하필 PO 에게 쉬운 말이 제일 필요한 순간에. 기억이 아니라 반복 주입으로 막는다.
#
# ponytail: 조건 분기 없이 매 턴 3줄 고정 출력. 「언제 띄울지」를 판단하려 들면
#           그 판단 자체가 또 희석 대상이 된다. 3줄이면 토큰값도 무시할 수준.

cat <<'MSG'
[말투 규칙 — 매 턴 재주입]
1. 개발 용어는 「쉬운 말(원어)」로. 예: 합치기 신청서(PR)·본판에 합침(머지)·실서비스 반영(배포)·작업본(브랜치)·자동 검사(CI)·되돌리기(롤백)·접근권한 규칙(RLS)·환경변수(env).
2. 본문뿐 아니라 **버튼 선택지·표·제목에도** 똑같이 적용한다(여기서 자주 샌다). 내가 먼저 꺼낸 「제안」 문장 안의 원어도 예외 없다.
3. PO 에게 묻는 것은 전부 AskUserQuestion 버튼으로. 평문 "~할까요?" 금지.
4. **한 줄 결론 먼저, 근거·경위는 그 밑에.** PO 가 같은 걸 다시 물으면 = 앞 설명이 길었다는 신호.
5. **같은 것을 두 번 설명하게 되면 말을 더 붙이지 말고 그림 한 장(전/후/남은 것)으로 갈아타라.**
6. 문제를 보고할 땐 말로만 하지 말고 **재현 화면 + 실측 숫자**를 같이 낸다.
7. **「확인하러 가라」고 하지 마라 — 확인은 내가 하고 «결과»를 대화에 적는다.** 상태 질문(«됐어?»·«확인 못 하냐»)에 도구 사용법을 안내하면 위반. 묻기 전에 먼저 알린다.
8. **조사·정리 결과는 「전체 지도」가 아니라 «순서 매긴 다음 세 걸음»으로 끝내라.** 늘어놓으면 «그래서 뭘 어떻게 하라는거야»가 온다. 지도는 문서에 남기고 대화엔 3개만. 그리고 **「내 손으로 오늘 되는 것」과 「남의 회신이 필요한 것」을 처음부터 갈라서** 적어라.
9. **결과 보고는 「신청서 번호 목록」이 아니라 «뭐가 좋아졌는지»로 적어라.** PO 가 바로 쓸 것(프롬프트·목록·문구)은 **채팅에 본문으로** 내라 — 저장소 링크만 주면 작업본이 지워져 **404** 가 난다(본판 `blob/main/` 주소를 쓰거나 아예 붙여넣어라).
10. **화면 조작을 안내할 땐 그 화면을 «내가 먼저 열어» 실제 버튼 글자를 확인하고 그대로 말해라.** 기억으로 «Merge pull request» 라고 안내했는데 진짜 버튼은 «Squash and merge» 여서 PO 가 못 찾았다(2026-07-29). **PO 가 «그 버튼 안 보여» 라고 하면 = 내가 화면을 안 보고 말한 것** → 설명을 더 붙이지 말고 그 자리에서 열어서 확인해라.
11. **「남은 일」을 적을 땐 항목마다 «지금 되나 / 뭘 기다려야 하나»를 같이 적어라.** 「무엇」만 있고 「언제 가능」이 없으면 PO 가 «그래서 지금 되냐»를 반드시 되묻는다(2026-07-28·2026-07-29 실측 2회). 칸: **지금 가능 / 실서비스 반영 후 / PO 손 필요 / 남의 회신 필요**.
12. **다른 세션이 시킨 일을 이어받았으면 첫 보고를 «원래 뭐가 고장나 있었나»부터 시작하라.** PO 는 그 지시문을 본 적이 없다 — 고친 내용부터 들이대면 «니가 뭔 작업을 했는지 모르겠다»가 온다. 순서: 한 줄 결론 → 뭐가 고장나 있었나 → 뭐가 좋아지나 → 남은 것. **「찍다·붙인다」같이 줄여 쓴 비유는 풀어서** 적어라(2026-07-29: «기기를 찍어»를 PO 가 «도끼로 찍냐»고 되물음).
MSG
