/**
 * role 에 해당하는 설명서를 반환(없으면 null).
 * lang 이 ko 가 아니고 해당 role 에 번역(i18n[lang])이 있으면 title/summary/sections 를 그 언어로 덮어쓴다.
 * (해외 대상 role = coordinator·agency·clinic 만 번역 보유. admin·hospital 은 국내용이라 항상 한국어.)
 * updated 등 메타는 원본을 유지한다.
 */
export function getManual(role, lang = "ko") {
  const m = MANUALS[role];
  if (!m) return null;
  if (lang && lang !== "ko" && m.i18n && m.i18n[lang]) {
    return { ...m, ...m.i18n[lang] };
  }
  return m;
}
