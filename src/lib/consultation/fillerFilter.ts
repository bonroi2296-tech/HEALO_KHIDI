/**
 * 원격협진 자막 추임새 필터
 *
 * "음", "어", "그…", "uh", "э-э" 같은 추임새만 있는 발화 조각이 각각 자막으로
 * 떠서 상대 화면이 지저분해지는 문제 해소용. 추임새**만** 있는 텍스트인지
 * 판별한다 — 실제 내용이 한 단어라도 섞여 있으면 통과 (자막 누락이 자막
 * 지저분함보다 훨씬 나쁘므로 보수적으로 동작).
 *
 * 사용처:
 * - 클라이언트(상담방): 브라우저 STT 최종 결과가 추임새뿐이면 번역 호출 자체를 스킵
 * - 서버 STT 라우트: 모델이 프롬프트 지시를 어기고 추임새를 전사해도 2차 차단
 */

// 6개 지원 언어(ko·en·ru/kz·zh·ja)의 대표적 추임새/망설임 소리.
// "네", "да", "yes" 같은 한 단어 대답은 의미가 있으므로 절대 포함하지 않는다.
const FILLER_TOKEN_RE = new RegExp(
  "^(?:" +
    [
      // 한국어
      "음+", "어+", "아+", "그+", "저+", "흠+", "에+", "엄+", "으+",
      // 영어
      "u+m+", "u+h+", "h+m+", "m+", "mhm+", "e+r+m*", "a+h+", "e+h+", "o+h+", "huh",
      // 러시아어 (카자흐어 STT 는 러시아어 폴백)
      "э+", "э+м+", "м+", "ну+", "гм+", "хм+", "а+", "о+",
      // 중국어
      "嗯+", "呃+", "啊+", "哦+", "唔+", "那个", "这个",
      // 일본어
      "え+ー*", "あ+ー*", "えっと+", "ええと+", "あの+ー*", "う+ー*ん", "ん+ー*",
    ].join("|") +
    ")$",
  "i"
);

// 토큰 분리 시 무시할 문장부호·기호 (말줄임표, 물결 등 STT가 붙이는 장식 포함)
const PUNCT_RE = /[.,!?…~\-—–·'"“”‘’()\[\]\s]+/g;

/** 텍스트가 추임새(망설임 소리)로만 이루어져 있으면 true */
export function isFillerOnly(text: string): boolean {
  if (!text) return true;
  const tokens = text.replace(PUNCT_RE, " ").trim().split(" ").filter(Boolean);
  if (tokens.length === 0) return true;
  return tokens.every((t) => FILLER_TOKEN_RE.test(t));
}
