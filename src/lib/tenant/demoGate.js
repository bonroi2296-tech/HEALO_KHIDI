/**
 * 병원 사이트 판(템플릿) 시연 화면을 **누구에게 보여줄지** 정하는 한 곳.
 *
 * 왜 파일을 따로 뺐나 (2026-07-29):
 *   같은 판정이 `app/demo/hospital/page.jsx` 와 `[slug]/page.jsx` 두 곳에 복사돼 있었다.
 *   한쪽만 고치면 목록은 보이는데 속 페이지는 404 가 되는 «반쪽 노출»이 난다. 그래서 한 곳으로 모았다.
 *
 * 규칙 (위에서부터 걸리는 첫 줄):
 *   ① `ALLOW_TEMPLATE_DEMO=1` 을 명시적으로 켰다  → 보인다 (기존 탈출구, 그대로 둔다)
 *   ② 실서비스 빌드가 아니다(로컬 개발)          → 보인다
 *   ③ Vercel **프리뷰** 빌드다                   → 보인다  ← 2026-07-29 추가
 *   ④ 그 밖(= 실서비스)                          → 안 보인다(404)
 *
 * ③을 왜 더했나 — PO 가 *"그럼 지금까지 만든건 어디서 보니?"* 라고 물었을 때 **볼 곳이 없었다.**
 *   실서비스는 막혀 있고(맞다), 프리뷰도 「실서비스 모드」로 돌아서 똑같이 404 였다.
 *   이 컨테이너의 개발 서버는 바깥에서 닿을 주소가 없다(터널 도구 전무 — 실측 확인).
 *   즉 **판을 만들어 놓고 만든 사람만 볼 수 있는** 상태였다. 그건 검토가 불가능하다는 뜻이다.
 *
 * ⚠️ 이건 «실서비스를 여는 것»이 아니다. `VERCEL_ENV` 는 Vercel 이 붙이는 값이고
 *    실서비스 배포는 `production` 이라 ④에 걸려 계속 404 다. `tenant.test.ts` 가 그걸 지킨다.
 * ⚠️ 프리뷰 주소는 **검색에 안 걸리지만(robots noindex) 주소를 아는 사람은 열 수 있다.**
 *    그래서 이 화면은 ①`isMockup: true` 표식 ②법인정보 빈칸(지어낸 값 없음)
 *    ③푸터에 「판 시연용 목업」 문구를 달고 있다 — 우연히 들어온 사람이 병원 실사이트로 오해하지 않게.
 */
export function isTemplateDemoVisible(env = process.env) {
  if (env.ALLOW_TEMPLATE_DEMO === "1") return true;
  if (env.NODE_ENV !== "production") return true;
  return env.VERCEL_ENV === "preview";
}
