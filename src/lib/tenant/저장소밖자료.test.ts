import { describe, it, expect } from "vitest";
import { execFileSync } from "node:child_process";
import fs from "node:fs";

/**
 * 🔴 **환자 얼굴이 공개 저장소에 올라가는 것을 막는 자물쇠.**
 *
 * 왜 필요한가 (2026-07-30):
 *   PO 요청으로 병원이 준 원본 사진·영상 보관함(`_병원자료/`)을 **저장소 폴더 안**에 둔다.
 *   그런데 이 저장소는 **공개(public)** 이고, 2분마다 도는 자동저장 훅이 `git add -A` 다.
 *   즉 **폴더에 파일이 들어온 순간 다음 사이클에 인터넷에 공개된다.**
 *   그 보관함에는 **환자 얼굴이 그대로 나온 촬영 원본**이 섞여 있다(병원 아카이브 특성이다 —
 *   `16_모닝요가` 폴더의 「최종」이 전부 `얼굴합성*.png` 였던 이유가 그것이다).
 *   한 번 올라가면 지워도 **커밋 이력에 남는다 → 되돌릴 수 없다.**
 *
 * 겹이 셋이어야 하는 이유:
 *   ① `.gitignore` 한 줄 — 첫 겹. 그런데 **한 줄이라 실수로 지워지거나 규칙이 안 먹을 수 있다**
 *      (예: 파일이 이미 추적 중이면 `.gitignore` 는 무력하다 — 이게 제일 흔한 함정).
 *   ② 이 검사 — **말이 아니라 실제로 깃이 무엇을 들고 있는지** 본다.
 *   ③ `next.config.js` 의 감시 제외 — 이건 안전이 아니라 속도용(개발 서버가 안 느려지게).
 *
 * ⚠️ 이 검사가 빨개지면 «검사를 고치는» 게 아니라 **그 파일을 깃에서 빼야 한다.**
 *    (추적 해제: `git rm -r --cached _병원자료`. 이미 밀어 올렸다면 이력까지 지워야 하므로
 *     그 시점에 바로 알려라 — 시간이 지날수록 되돌리기가 어려워진다.)
 */
const 보관함 = "_병원자료";

const 깃추적목록 = (경로: string) => {
  try {
    return execFileSync("git", ["ls-files", "-z", "--", 경로], { encoding: "utf8" })
      .split("\0")
      .filter(Boolean);
  } catch {
    return []; // 깃이 없는 환경(있을 수 없지만)에서 검사가 터지지 않게
  }
};

describe("🔴 병원 원본 자료가 공개 저장소에 올라가지 않는다", () => {
  it("`.gitignore` 에 보관함이 등록돼 있다", () => {
    const 무시 = fs.readFileSync(".gitignore", "utf8");
    expect(무시, `.gitignore 에 \`${보관함}/\` 가 없다 — 자동저장 훅이 다음 사이클에 공개한다`).toContain(
      `${보관함}/`,
    );
  });

  it("깃이 보관함 안의 파일을 하나도 추적하지 않는다", () => {
    const 추적중 = 깃추적목록(보관함);
    expect(
      추적중.slice(0, 20),
      `보관함 파일이 깃에 들어갔다(${추적중.length}개). ` +
        `«.gitignore 에 적었다»로 끝나지 않는다 — 이미 추적 중이면 무시 규칙이 안 먹는다. ` +
        `\`git rm -r --cached ${보관함}\` 로 빼고, 이미 밀어 올렸다면 즉시 알려라.`,
    ).toEqual([]);
  });

  it("무시 규칙이 실제로 작동한다 (말이 아니라 깃에게 직접 물어본다)", () => {
    /* `.gitignore` 에 글자가 있는 것과 깃이 실제로 무시하는 것은 다르다.
       (앞선 규칙이 되받아치거나 `!` 예외가 뒤에 붙어 있을 수 있다.)
       그래서 가짜 경로를 하나 만들어 «너 이거 무시하냐»고 깃에게 직접 묻는다. */
    let 무시하나 = false;
    try {
      execFileSync("git", ["check-ignore", "-q", `${보관함}/원본/사진.jpg`], { stdio: "ignore" });
      무시하나 = true; // 종료코드 0 = 무시함
    } catch {
      무시하나 = false;
    }
    expect(
      무시하나,
      `깃이 \`${보관함}/\` 를 무시하지 않는다 — .gitignore 에 글자만 있고 실제로는 안 먹는 상태다`,
    ).toBe(true);
  });
});
