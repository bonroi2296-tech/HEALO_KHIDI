def 만들기(경로):
    from docx import Document
    from docx.shared import Pt, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml.ns import qn
    from docx.oxml import OxmlElement

    NAVY, RED, FONT = RGBColor(0x1F, 0x3B, 0x73), RGBColor(0xC0, 0x00, 0x00), "맑은 고딕"
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = FONT
    st.font.size = Pt(11)
    st._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)

    h = doc.add_paragraph(); h.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = h.add_run("2026년 ICT 기반 외국인환자 사전상담·사후관리 지원 사업\n중간보고회 발표 대본")
    r.font.size, r.font.bold, r.font.color.rgb = Pt(16), True, NAVY
    sub = doc.add_paragraph(); sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = sub.add_run("본로이 컨소시엄 · 2026. 09.  ·  발표자료 v4(17쪽) 기준  ·  발표 15분 + 질의응답")
    r.font.size, r.font.color.rgb = Pt(10), RGBColor(0x66, 0x66, 0x66)
    doc.add_paragraph()

    총글자 = 0
    for title, paras in SLIDES:
        p = doc.add_paragraph()
        p.paragraph_format.space_before, p.paragraph_format.space_after = Pt(14), Pt(4)
        r = p.add_run(title)
        r.font.size, r.font.bold, r.font.color.rgb = Pt(13), True, NAVY
        for txt in paras:
            # 별첨(예상 질문)은 발표 중에 읽지 않으므로 시간에서 뺀다
            읽음 = not (txt.startswith("[아래는") or "별첨" in title)
            if 읽음:
                총글자 += len(txt.replace("«", "").replace("»", ""))
            pp = doc.add_paragraph()
            pp.paragraph_format.space_after = Pt(3)
            pp.paragraph_format.line_spacing = 1.4
            for i, chunk in enumerate(txt.replace("»", "«").split("«")):
                if not chunk:
                    continue
                run = pp.add_run(chunk)
                run.font.size = Pt(11)
                if i % 2 == 1:
                    run.font.bold = True
                    run.font.color.rgb = RED

    for _p in doc.paragraphs:      # 한글과 숫자 사이 자동 간격 끄기
        _pPr = _p._p.get_or_add_pPr()
        for _tag in ("w:autoSpaceDE", "w:autoSpaceDN", "w:kinsoku"):
            _e = OxmlElement(_tag); _e.set(qn("w:val"), "0"); _pPr.append(_e)

    doc.save(경로)
    return 총글자


