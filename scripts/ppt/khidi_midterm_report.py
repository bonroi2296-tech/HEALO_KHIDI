def bullet(text, size=10, indent=0.4):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(indent)
    p.paragraph_format.space_after = Pt(2)
    r = p.add_run("○ " + text if indent < 0.5 else "- " + text)
    r.font.size, r.font.name = Pt(size), FONT
    r.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)


def table(rows, widths=None, size=9, header=True, align_center=False):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            cell = t.cell(ri, ci)
            cell.text = ""
            p = cell.paragraphs[0]
            p.paragraph_format.space_after = Pt(1)
            if align_center or (header and ri == 0):
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = p.add_run(str(val))
            r.font.size = Pt(size)
            r.font.bold = header and ri == 0
            r.font.name = FONT
            r.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
            if NEED in str(val):
                r.font.color.rgb = RGBColor(0xC0, 0x00, 0x00)
    if widths:
        for ci, w in enumerate(widths):
            for row in t.rows:
                row.cells[ci].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


