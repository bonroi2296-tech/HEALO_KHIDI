def set_para_text(p, text):
    """문단 하나의 글자를 바꾼다. 새로 만드는 요소는 <hp:t> 하나뿐이다."""
    runs = p.findall('./' + HP + 'run')
    if not runs:
        return False
    drop_linesegs(p)
    for r in runs:
        normalize_charpr(r)
    done = False
    for run in runs:
        ts = run.findall('./' + HP + 't')
        if not done:
            if ts:
                wipe(ts[0])
                ts[0].text = text
                for extra in ts[1:]:
                    wipe(extra)
            else:
                etree.SubElement(run, HP + 't').text = text
            done = True
        else:
            for t in ts:
                wipe(t)
    return done


def set_cell_text(tc, text):
    ps = tc.findall('.//' + HP + 'p')
    if not ps:
        return False
    ok = set_para_text(ps[0], text)
    for p in ps[1:]:
        set_para_text(p, '')
    return ok


