def wipe(t):
    """<hp:t> 안의 글자를 비운다.

    ⚠️ .text 만 지우면 안 된다 — 형광펜·글자겹침 같은 표시가 <hp:t> 안에 자식으로 들어가 있고,
    「성과목표」 같은 안내 글자가 그 «자식 뒤 꼬리(tail)»에 붙어 있는 경우가 있다.
    (2026-08-18 실측: 이걸 놓쳐서 채운 글 뒤에 옛 안내 글자가 그대로 남았다.)
    """
    t.text = ''
    for child in t:
        child.tail = ''


def drop_linesegs(p):
    """줄 나눔 «캐시»(<hp:linesegarray>)를 지운다.

    ⚠️ 이걸 안 지우면 한글이 «빈 칸이던 시절의 줄 배치»를 그대로 믿고 그려서
    새로 넣은 긴 글이 한 줄에 겹쳐 찍힌다(2026-08-18 실측, PO 화면 재현).
    이 값은 한글이 문서를 열 때 다시 계산하는 캐시라 지워도 안전하다.
    """
    for ls in p.findall('./' + HP + 'linesegarray'):
        p.remove(ls)


