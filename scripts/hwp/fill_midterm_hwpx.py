# ════════════════════════════════════════════ 채우기
def wipe(t):
    """<hp:t> 안의 글자를 비운다 (자식 뒤 꼬리까지)."""
    t.text = ''
    for child in t:
        child.tail = ''


def drop_linesegs(p):
    """줄 나눔 «미리계산값»을 지운다 — 안 지우면 글자가 겹쳐 찍힌다."""
    for ls in p.findall('./' + HP + 'linesegarray'):
        p.remove(ls)


def normalize_charpr(run):
    """「예시」용 빨강·기울임 글자모양을 같은 크기의 검정 정자로 바꾼다."""
    cid = run.get('charPrIDRef')
    if cid in CHAR_FIX:
        run.set('charPrIDRef', CHAR_FIX[cid])


def set_para_text(p, text):
    runs = p.findall('./' + HP + 'run')
    if not runs:
        return False
    drop_linesegs(p)
    for r in runs:
        normalize_charpr(r)
    done = False
    for run in runs:
        ts = run.findall('./' + HP + 't')
        if not done:
            if ts:
                wipe(ts[0])
                ts[0].text = text
                for extra in ts[1:]:
                    wipe(extra)
            else:
                etree.SubElement(run, HP + 't').text = text
            done = True
        else:
            for t in ts:
                wipe(t)
    return done


def set_cell_text(tc, text):
    ps = tc.findall('.//' + HP + 'p')
    if not ps:
        return False
    ok = set_para_text(ps[0], text)
    for p in ps[1:]:
        set_para_text(p, '')
    return ok


def clone_rows(tbl, src_row, times):
    """표의 한 행을 복제해 행을 늘린다. 복제 후 rowAddr·rowCnt 를 다시 매긴다."""
    trs = tbl.findall('./' + HP + 'tr')
    src = trs[src_row]
    pos = list(tbl).index(src)
    for k in range(times):
        tbl.insert(pos + 1 + k, copy.deepcopy(src))
    for ri, tr in enumerate(tbl.findall('./' + HP + 'tr')):
        for tc in tr.findall('./' + HP + 'tc'):
            ca = tc.find('./' + HP + 'cellAddr')
            if ca is not None:
                ca.set('rowAddr', str(ri))
    tbl.set('rowCnt', str(len(tbl.findall('./' + HP + 'tr'))))


LINE_H = 2712   # 표 안 한 줄 높이(양식 실측)
CHAR_W = 960    # 한글 한 글자 폭(양식 실측)


def disp_len(s):
    """화면에서 차지하는 폭 — 한글·전각은 1, 그 밖은 0.55로 센다."""
    return sum(1.0 if ord(c) > 0x1100 else 0.55 for c in s)


def cell_text(tc):
    return ''.join(x for t in tc.iter(HP + 't') for x in [t.text or ''] + [c.tail or '' for c in t])


def refit_table(tbl):
    """칸 높이를 «내용에 맞게» 다시 잡는다.

    ⚠️ 양식의 칸 높이는 고정값이다. 글을 길게 넣으면 넘친 부분이 그냥 «안 그려진다» —
    2026-08-18 실측: 「성과(물) 활용계획」·「문제점 및 건의」 행과 계획대비표 8월 행이 통째로 사라졌다.
    한글이 알아서 늘려주지 않으므로 여기서 미리 계산해 넣는다.
    """
    trs = tbl.findall('./' + HP + 'tr')
    rows = len(trs)
    cells = []
    for tr in trs:
        for tc in tr.findall('./' + HP + 'tc'):
            ca, sp, sz = (tc.find('./' + HP + x) for x in ('cellAddr', 'cellSpan', 'cellSz'))
            if ca is None or sz is None:
                continue
            r = int(ca.get('rowAddr'))
            rs = int(sp.get('rowSpan')) if sp is not None else 1
            w = int(sz.get('width'))
            per = max(4.0, (w - 400) / CHAR_W)
            need = max(1, -(-int(disp_len(cell_text(tc)) * 100) // int(per * 100))) * LINE_H
            cells.append((tc, sz, r, rs, need, int(sz.get('height'))))

    row_h = [0] * rows
    for tc, sz, r, rs, need, old in cells:
        if rs == 1:
            row_h[r] = max(row_h[r], need, old)
    for r in range(rows):
        if row_h[r] == 0:
            row_h[r] = LINE_H
    # 세로로 합쳐진 칸이 모자라면 마지막 걸친 행을 키운다
    for tc, sz, r, rs, need, old in cells:
        if rs > 1:
            have = sum(row_h[r:r + rs])
            if have < need:
                row_h[r + rs - 1] += need - have

    for tc, sz, r, rs, need, old in cells:
        sz.set('height', str(sum(row_h[r:r + rs])))
    tsz = tbl.find('./' + HP + 'sz')
    if tsz is not None:
        tsz.set('height', str(sum(row_h)))


def build_char_fix(zf):
    hdr = etree.fromstring(zf.read('Contents/header.xml'))
    info, plain = {}, {}
    for cp in hdr.findall('.//' + HH + 'charPr'):
        cid = cp.get('id')
        key = (cp.get('height'), cp.find('./' + HH + 'bold') is not None)
        color = (cp.get('textColor') or '#000000').upper()
        italic = cp.find('./' + HH + 'italic') is not None
        info[cid] = (key, color, italic)
        if color == '#000000' and not italic:
            plain.setdefault(key, cid)
    return {cid: plain[key] for cid, (key, color, italic) in info.items()
            if (color != '#000000' or italic) and key in plain}


