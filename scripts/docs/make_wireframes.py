W, H = 1000, 760
INK = (40, 40, 40)
GRAY = (130, 130, 130)
LINE = (150, 150, 150)
FILL = (240, 240, 240)
FILL2 = (225, 225, 225)
WHITE = (255, 255, 255)


def font(sz, bold=False):
    p = r'C:\Windows\Fonts\malgunbd.ttf' if bold else r'C:\Windows\Fonts\malgun.ttf'
    return ImageFont.truetype(p, sz)


F, FB, FS = font(15), font(15, True), font(12)


def new():
    img = Image.new('RGB', (W, H), WHITE)
    return img, ImageDraw.Draw(img)


def title(d, no, name, service):
    d.rectangle([0, 0, W, 54], fill=(250, 250, 250), outline=LINE)
    d.text((18, 12), '화면 %s   %s' % (no, name), font=font(19, True), fill=INK)
    d.text((18, 34), service, font=FS, fill=GRAY)


def box(d, x, y, w, h, label='', sub='', fill=FILL, dash=False, center=True):
    d.rectangle([x, y, x + w, y + h], fill=fill, outline=LINE, width=1)
    if dash:  # 아직 화면에 안 붙은 것
        for i in range(x, x + w, 12):
            d.line([i, y, min(i + 6, x + w), y], fill=GRAY, width=2)
    if label:
        f = FB if len(label) < 30 else F
        lines = label.split('\n')
        base = y + (h / 2 - 16 if sub else h / 2 - 9) - (len(lines) - 1) * 9
        for i, ln in enumerate(lines):
            tw = d.textlength(ln, font=f)
            tx = x + (w - tw) / 2 if center else x + 10
            d.text((tx, base + i * 18), ln, font=f, fill=INK)
    if sub:
        for i, ln in enumerate(sub.split('\n')):
            tw = d.textlength(ln, font=FS)
            tx = x + (w - tw) / 2 if center else x + 10
            d.text((tx, y + h / 2 + 4 + i * 16), ln, font=FS, fill=GRAY)


def note(d, y, text):
    d.text((18, y), text, font=FS, fill=GRAY)


def arrow(d, x1, y1, x2, y2, label=''):
    d.line([x1, y1, x2, y2], fill=GRAY, width=2)
    import math
    a = math.atan2(y2 - y1, x2 - x1)
    for s in (0.5, -0.5):
        d.line([x2, y2, x2 - 10 * math.cos(a - s), y2 - 10 * math.sin(a - s)], fill=GRAY, width=2)
    if label:
        d.text(((x1 + x2) / 2 - d.textlength(label, font=FS) / 2, (y1 + y2) / 2 - 16), label, font=FS, fill=GRAY)


