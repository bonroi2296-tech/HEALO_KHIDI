def set_cell_bg(cell, hexc):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear'); shd.set(qn('w:color'), 'auto'); shd.set(qn('w:fill'), hexc)
    tcPr.append(shd)


def table(headers, widths=None, hsize=8.5):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ''
        p = c.paragraphs[0]; p.paragraph_format.space_after = Pt(0)
        set_font(p.add_run(h), size=hsize, bold=True, color=(255, 255, 255))
        set_cell_bg(c, NAVY)
    if widths:
        for i, w in enumerate(widths):
            t.rows[0].cells[i].width = Cm(w)
    t._w = widths
    return t


def row(t, cols, size=8.6, bold_first=False, shade=None, center=()):
    r = t.add_row()
    for i, c in enumerate(r.cells):
        if i >= len(cols):
            continue
        c.text = ''
        p = c.paragraphs[0]; p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.line_spacing = 1.25
        set_font(p.add_run(str(cols[i])), size=size, bold=(bold_first and i == 0))
        if i in center:
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        if shade:
            set_cell_bg(c, shade)
        if getattr(t, '_w', None):
            c.width = Cm(t._w[i])
    return r


